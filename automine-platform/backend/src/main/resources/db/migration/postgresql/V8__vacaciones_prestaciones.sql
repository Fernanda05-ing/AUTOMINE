-- Vacaciones: 15 dias habiles por año laborado (CST art. 186)
CREATE TABLE vacaciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id    BIGINT        NOT NULL,
    fecha_inicio   DATE          NOT NULL,
    fecha_fin      DATE          NOT NULL,
    fecha_regreso  DATE          NOT NULL,
    dias_habiles   INT           NOT NULL,
    observaciones  VARCHAR(500),
    estado         VARCHAR(20)   NOT NULL,
    motivo_rechazo VARCHAR(500),
    solicitado_por VARCHAR(150)  NOT NULL,
    revisado_por   VARCHAR(150),
    fecha_revision TIMESTAMP,
    created_at     TIMESTAMP      NOT NULL,
    CONSTRAINT fk_vacaciones_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);
CREATE INDEX ix_vacaciones_empleado ON vacaciones (empleado_id, estado);

-- Prima de servicios, cesantias e intereses liquidados por periodo
CREATE TABLE pagos_prestaciones (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id  BIGINT        NOT NULL,
    tipo         VARCHAR(20)   NOT NULL,
    anio         INT           NOT NULL,
    periodo      INT           NOT NULL,
    fecha_desde  DATE          NOT NULL,
    fecha_hasta  DATE          NOT NULL,
    base         DECIMAL(15,2) NOT NULL,
    dias         INT           NOT NULL,
    valor        DECIMAL(15,2) NOT NULL,
    liquidado_por VARCHAR(150) NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    CONSTRAINT uk_pago_prestacion UNIQUE (empleado_id, tipo, anio, periodo),
    CONSTRAINT fk_pago_prestacion_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);

-- Liquidacion final del contrato
CREATE TABLE liquidaciones_retiro (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id         BIGINT        NOT NULL,
    fecha_retiro        DATE          NOT NULL,
    motivo              VARCHAR(30)   NOT NULL,
    observaciones       VARCHAR(500),
    salario_base        DECIMAL(15,2) NOT NULL,
    base_prestaciones   DECIMAL(15,2) NOT NULL,
    dias_salario        INT           NOT NULL,
    salario_pendiente   DECIMAL(15,2) NOT NULL,
    dias_prima          INT           NOT NULL,
    prima               DECIMAL(15,2) NOT NULL,
    dias_cesantias      INT           NOT NULL,
    cesantias           DECIMAL(15,2) NOT NULL,
    intereses_cesantias DECIMAL(15,2) NOT NULL,
    dias_vacaciones     DECIMAL(8,2)  NOT NULL,
    vacaciones          DECIMAL(15,2) NOT NULL,
    indemnizacion       DECIMAL(15,2) NOT NULL,
    total               DECIMAL(15,2) NOT NULL,
    liquidado_por       VARCHAR(150)  NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    CONSTRAINT uk_liquidacion_empleado UNIQUE (empleado_id, fecha_retiro),
    CONSTRAINT fk_liquidacion_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);

