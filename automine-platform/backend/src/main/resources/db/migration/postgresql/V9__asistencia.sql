-- Plantilla facial de cada trabajador (dato biometrico sensible, Ley 1581 de 2012):
-- solo se guarda con autorizacion expresa y se borra al retirarse el trabajador.
CREATE TABLE rostros (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id         BIGINT        NOT NULL,
    plantilla           TEXT          NOT NULL,
    version_modelo      VARCHAR(40)   NOT NULL,
    foto                BYTEA      NOT NULL,
    autorizacion_fecha  TIMESTAMP      NOT NULL,
    autorizacion_texto  VARCHAR(600)  NOT NULL,
    registrado_por      VARCHAR(150)  NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    CONSTRAINT uk_rostro_empleado UNIQUE (empleado_id),
    CONSTRAINT fk_rostro_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);

-- Entradas y salidas registradas por SG-SST
CREATE TABLE marcaciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id    BIGINT        NOT NULL,
    tipo           VARCHAR(10)   NOT NULL,
    fecha_hora     TIMESTAMP      NOT NULL,
    metodo         VARCHAR(20)   NOT NULL,
    similitud      DECIMAL(5,4),
    foto           BYTEA,
    observacion    VARCHAR(300),
    anulada        BOOLEAN       NOT NULL,
    registrado_por VARCHAR(150)  NOT NULL,
    dispositivo_id VARCHAR(80),
    created_at     TIMESTAMP      NOT NULL,
    CONSTRAINT uk_marcacion_dispositivo UNIQUE (dispositivo_id),
    CONSTRAINT fk_marcacion_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id)
);
CREATE INDEX ix_marcaciones_fecha ON marcaciones (fecha_hora);
CREATE INDEX ix_marcaciones_empleado ON marcaciones (empleado_id, fecha_hora);

